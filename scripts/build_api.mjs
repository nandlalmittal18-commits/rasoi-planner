// Bundle server/*.ts into single files in api/ that Vercel runs as functions.
// Run after changing server/ or src/engine/: npm run api   (then commit api/ too)
import { writeFileSync, mkdirSync } from 'node:fs';
import { rolldown } from 'rolldown';

mkdirSync('api', { recursive: true });

for (const name of ['cook-daily']) {
  const bundle = await rolldown({ input: `server/${name}.ts`, platform: 'node' });
  const { output } = await bundle.generate({ format: 'esm' });
  const note = `// Generated by scripts/build_api.mjs from server/${name}.ts. Do not edit this file; edit the source and run \`npm run api\`.\n`;
  writeFileSync(`api/${name}.js`, note + output[0].code);
  await bundle.close();
  console.log(`built api/${name}.js`);
}
